"""Write inputs.md: every input file read by the reproduction scripts (path, size, sha256, modification date) and the
outputs that depend on it. Built from the out/_manifest_<script>.json files each script writes; run it last."""
import datetime
import glob
import json
import os

from repro_common import HERE, OUT, ROOT, sha256

SCRIPTS = {"make_table3": "make_table3.py", "make_fig3": "make_fig3.py", "make_fig4": "make_fig4.py",
           "check_against_paper": "check_against_paper.py"}


def rel(p):
    return os.path.relpath(p, ROOT) if p.startswith(ROOT + os.sep) else p


def main():
    deps = {}
    for f in sorted(glob.glob(os.path.join(OUT, "_manifest_*.json"))):
        m = json.load(open(f, encoding="utf-8"))
        for p, outs in m["inputs"].items():
            d = deps.setdefault(p, dict(outputs=set(), scripts=set()))
            d["outputs"].update(outs)
            d["scripts"].add(SCRIPTS.get(m["script"], m["script"]))
    stats = {}
    for p in deps:
        st = os.stat(p)
        stats[p] = (st.st_size, sha256(p), datetime.datetime.fromtimestamp(st.st_mtime, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"))
    runs = sorted(p for p in deps if "/libero/out/runs/" in p)
    other = sorted(p for p in deps if p not in runs)
    contrib = {}
    try:
        contrib = json.load(open(os.path.join(OUT, "fig3_stats.json"), encoding="utf-8"))["fig3b"]["data_source"][
            "files_contributing_to_plotted_levels"]
    except (OSError, KeyError):
        pass
    L = ["# Inputs of the paper reproduction (Table 3, Fig. 3a/3b, Fig. 4)", "",
         f"Generated by `make_inputs.py` on {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}. "
         f"Paths are relative to the project root `{ROOT}` (`$WMV_ROOT`). All inputs are opened read-only. "
         "Dates are file modification times.", "",
         "## Tables, main table, registry, paper values", "",
         "| file | size (bytes) | sha256 | modified | read by | outputs that depend on it |", "|---|---|---|---|---|---|"]
    for p in other:
        s, h, t = stats[p]
        L.append(f"| `{rel(p)}` | {s} | `{h}` | {t} | {', '.join(sorted(deps[p]['scripts']))} | {', '.join(sorted(deps[p]['outputs']))} |")
    tot = sum(stats[p][0] for p in runs)
    L += ["", "## Original 50-unit open-loop records (Fig. 3b plan axis)", "",
          f"{len(runs)} files, {tot} bytes in total, read by `make_fig3.py`; outputs: fig3b.pdf, fig3b.png, fig3b_points.tsv, "
          "fig3_stats.json. All of them are scanned (first record per unit_id wins, in the glob order given in make_fig3.py); "
          "the column 'units in plotted levels' counts the units each file contributes to the 435 plotted levels "
          "(0 = the file only holds excluded levels such as NL/NLw or sham rows, or units already seen in an earlier file). "
          "These are NOT the 2026-11-19 reduced-study records (`libero/out/openloop5_20261119/`).", "",
          "| file | size (bytes) | sha256 | modified | units in plotted levels |", "|---|---|---|---|---|"]
    for p in runs:
        s, h, t = stats[p]
        L.append(f"| `{rel(p)}` | {s} | `{h}` | {t} | {contrib.get(os.path.relpath(p, os.path.join(ROOT, 'libero', 'out', 'runs')), 0)} |")
    L += ["", "## Scripts", "", "| script | sha256 |", "|---|---|"]
    for s in ["repro_common.py", "plotlib.py", "make_table3.py", "make_fig3.py", "make_fig4.py", "check_against_paper.py",
              "make_inputs.py", "run_all.sh"]:
        L.append(f"| `{s}` | `{sha256(os.path.join(HERE, s))}` |")
    open(os.path.join(HERE, "inputs.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"inputs.md: {len(other)} files + {len(runs)} open-loop record files")


if __name__ == "__main__":
    main()
